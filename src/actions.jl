# prepare and submit: what the tool does on a site.

stamp() = Dates.format(now(), dateformat"yyyymmdd-HHMMSS")

prepared_file(site::Site, study) = joinpath(study_code(site, study), "prepared")
combo_line((project, args)) = isempty(args) ? project : project * "\t" * args

"The jobs the given spec files mean on a site."
function load_jobs(study, site::Site, specs; queue = nothing, only_runs = String[])
    snap = load_snapshot(study)
    return [resolve(load_spec(file), site; study, project = snap["project"], queue, only_runs, file)
            for file in specs]
end

"The bash script that makes a study runnable on a site."
function prepare_script(site::Site, study, needed)
    code, scratch = study_code(site, study), study_scratch(site, study)
    io = IOBuffer()
    print(io, """
          #!/bin/bash
          # Generated by SimLaunch $VERSION_STRING: prepare study $study on site $(site.name).
          # Instantiates and precompiles on this node; a job needs no network afterwards.

          set -euo pipefail

          CODE=$(shpath(code))
          SCRATCH=$(shpath(scratch))
          JULIA=$(shpath(site.julia_bin))

          mkdir -p "\$SCRATCH" "\$CODE/jobs"
          exec > >(tee -a "\$SCRATCH/prepare.log") 2>&1
          echo "=== prepare $study on $(site.name), host \$(hostname -s), \$(date) ==="

          unset JULIA_LOAD_PATH JULIA_PROJECT
          export JULIA_PKG_PRECOMPILE_AUTO=0
          """)
    site.precompile_tasks === nothing || println(io, "export JULIA_NUM_PRECOMPILE_TASKS=$(site.precompile_tasks)")
    for m in site.modules
        println(io, "module load $(q(m))")
    end
    update = site.registry_update ? "Pkg.Registry.update(); " : ""
    for project in unique!([p for (p, _) in needed])
        print(io, """

              echo "=== instantiate $project ==="
              "\$JULIA" --startup-file=no --project="\$CODE"/$(q(joinpath("src", project))) -e 'using Pkg; $(update)Pkg.instantiate()'
              """)
    end
    for combo in needed
        project, args = combo
        flags = isempty(args) ? "" : args * " "
        print(io, """

              echo "=== precompile $project $(isempty(args) ? "" : "with $args ")==="
              "\$JULIA" $(flags)--startup-file=no --project="\$CODE"/$(q(joinpath("src", project))) -e 'using Pkg; Pkg.precompile()'
              "\$JULIA" $(flags)--startup-file=no --project="\$CODE"/$(q(joinpath("src", project))) "\$CODE"/tools/check_precompiled.jl
              grep -qxF $(q(combo_line(combo))) "\$CODE/prepared" 2>/dev/null || echo $(q(combo_line(combo))) >> "\$CODE/prepared"
              """)
    end
    println(io)
    println(io, "echo \"=== prepared, \$(date) ===\"")
    return String(take!(io))
end

"""
    prepare(study; site, specs = [])

Copy the study to the site, instantiate it there, and precompile it for the
default flags and for what the given specs need.
"""
function prepare(study::AbstractString; site::AbstractString, specs = String[])
    s = load_site(site)
    snap = load_snapshot(study)
    s.precompile_on == "login" ||
        fail("site $(s.name) precompiles on a compute node, which is not implemented yet (milestone 2)")
    needed = [(snap["project"], "")]
    for job in load_jobs(study, s, specs)
        append!(needed, combos(job))
    end
    unique!(needed)
    check_connection(s)

    code = study_code(s, study)
    println("copying study $study to $(s.name):$code")
    push_tree(s, joinpath(cache_root(), study), code)
    script = prepare_script(s, study, needed)
    name = "prepare-$(stamp()).sh"
    mktempdir() do dir
        write(joinpath(dir, name), script)
        push_file(s, joinpath(dir, name), joinpath(code, "jobs", name))
    end
    println("preparing on $(s.name); log in $(joinpath(study_scratch(s, study), "prepare.log"))")
    ok = success(pipeline(sitecmd(s, "bash " * q(joinpath(code, "jobs", name))); stdout, stderr))
    ok || fail("prepare failed on $(s.name); see the output above")
    return
end

"The combinations prepared on the site so far."
function prepared(site::Site, study)
    out = readsite(site, "cat " * q(prepared_file(site, study)) * " 2>/dev/null || true")
    return Set(split(out, '\n'; keepempty = false))
end

function describe(io::IO, job::Job)
    println(io, "study $(job.study), spec $(job.name), site $(job.site.name)")
    job.queue === nothing || println(io, "queue: $(job.queue.partition)")
    println(io, "time: ", job.time === nothing ? "no limit" : time_string(job.time))
    println(io, "runs ($(job.mode)):")
    for r in job.runs
        println(io, "  $(rpad(r.label, 16)) $(lpad(r.threads, 4)) threads   ", join(r.cmd, " "))
    end
    return
end

"""
    submit(study, spec; site, queue = nothing, only_runs = [], dry_run = false)

Generate the job's batch script and submit it. With `dry_run` it is only
printed. `only_runs` submits just the runs with these labels. Returns the job ID, or `nothing` for a dry run.
"""
function submit(study::AbstractString, spec::AbstractString; site::AbstractString, queue = nothing,
                only_runs = String[], dry_run::Bool = false, io::IO = stdout)
    s = load_site(site)
    job = only(load_jobs(study, s, [spec]; queue, only_runs))
    script = generate(job)
    if dry_run
        describe(io, job)
        println(io, "--- the batch script ---")
        print(io, script)
        return nothing
    end

    check_connection(s)
    have = prepared(s, study)
    for combo in combos(job)
        combo_line(combo) in have && continue
        project, args = combo
        fail("study $study is not prepared on $(s.name) for $project", isempty(args) ? "" : " with $args",
             "; run `simlaunch prepare $study --site $(s.name) --spec $spec`")
    end

    code, scratch = study_code(s, study), study_scratch(s, study)
    base = "$(job.name)-$(stamp())"
    remote = joinpath(code, "jobs", base * ".sh")
    mktempdir() do dir
        write(joinpath(dir, base * ".sh"), script)
        push_file(s, joinpath(dir, base * ".sh"), remote)
        push_file(s, spec, joinpath(code, "jobs", base * ".toml"))
    end
    runsite(s, "mkdir -p " * q(joinpath(scratch, "logs")))
    if s.slurm
        export_flag = s.export_env ? "" : "--export=NONE "
        out = readsite(s, "sbatch --parsable $export_flag" * q(remote))
        jobid = String(first(split(strip(out), ';')))
        occursin(r"^\d+$", jobid) || fail("sbatch did not return a job ID: $(repr(out))")
        runsite(s, "bash " * q(remote) * " --queued " * q(jobid))
    else
        jobid = "L" * stamp()
        runsite(s, "bash " * q(remote) * " --queued " * q(jobid))
        log = log_file(job, jobid)
        runsite(s, "SIMLAUNCH_JOB_ID=$(q(jobid)) nohup bash $(q(remote)) > $(q(log)) 2>&1 < /dev/null &")
    end
    describe(io, job)
    println(io, "submitted as job $jobid; script $remote")
    println(io, "log: ", log_file(job, jobid))
    println(io, "watch with: simwatch ", islocal(s) ? scratch : "$(s.host):$scratch")
    return jobid
end
